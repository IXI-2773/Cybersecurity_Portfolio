'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
assert.ok(fs.existsSync(path.join(root, 'assets/js/test-engine.js')), 'Public browser test engine must exist');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/lab-data.js'), 'utf8'), context);
vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/test-engine.js'), 'utf8'), context);
const engine = context.PortfolioEngine;
const data = context.PortfolioLabData;
const canonical = x => JSON.parse(JSON.stringify(x));
assert.deepEqual(canonical(engine.detectAuth(data.events)), canonical(data.expected));
assert.equal(engine.detectAuth(data.events, {windowSeconds:599}).length, 3);
assert.equal(engine.detectAuth(data.events, {windowSeconds:600}).length, 5);
const checks = engine.runChecks(data);
assert.equal(checks.length, 9);
assert.equal(checks.filter(x => x.passed).length, 9);
assert.throws(() => engine.detectAuth(data.events, {windowSeconds: 0}), /positive integer/);
assert.throws(() => engine.detectAuth(data.events, {threshold: NaN}), /positive integer/);
assert.throws(() => engine.detectAuth([{timestamp: 'bad'}]), /event/);
assert.throws(() => engine.checkCoverage([{source: 'A', value: 4}, {source: 'A', value: 6}], []), /unique/);
assert.equal(engine.checkCoverage([], []).status, 'HOLD_NO_EVIDENCE');
assert.equal(engine.checkCoverage([{source:'A',value:4}], [{source:'A',value:4},{source:'X',value:9}]).status, 'HOLD_UNSUPPORTED_SOURCE');
assert.equal(engine.checkCoverage([{source:'A',value:4}], [{source:'A',value:4},{source:'A',value:4}]).status, 'HOLD_DUPLICATE_ATTRIBUTION');
assert.equal(engine.checkCoverage([{source:'A',value:4}], [{source:'A',value:4}]).status, 'PASS_COVERAGE');
console.log('PASS: 9 public engine checks, frozen-matrix parity, invalid inputs and unsupported/duplicate source controls');
