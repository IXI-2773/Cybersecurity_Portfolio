"""Derive the offline browser replay fixture from the public CSV and frozen oracle."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / 'projects/01-authentication-detection/validation_events.csv'
ORACLE_PATH = ROOT / 'projects/01-authentication-detection/expected_findings.json'
DEST = ROOT / 'assets/js/lab-data.js'

def render():
    with CSV_PATH.open(newline='', encoding='utf-8') as source:
        events = list(csv.DictReader(source))
    data = {
        'schema': 'portfolio.browser-fixture.v1',
        'scope': 'Synthetic public authentication training fixture; not production telemetry',
        'sources': [{
            'path': p.relative_to(ROOT).as_posix(),
            'sha256': hashlib.sha256(p.read_bytes()).hexdigest(),
        } for p in (CSV_PATH, ORACLE_PATH)],
        'events': events,
        'expected': json.loads(ORACLE_PATH.read_text())['expected_findings'],
    }
    return '// Generated by scripts/build_browser_fixture.py; edit the source fixtures instead.\n' + 'globalThis.PortfolioLabData = ' + json.dumps(data, indent=2, ensure_ascii=True) + ';\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not DEST.is_file() or DEST.read_text() != expected:
            raise SystemExit('Browser fixture is stale: run python scripts/build_browser_fixture.py')
        print('PASS: browser fixture matches authoritative CSV/oracle bytes and SHA-256 records')
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(expected)
        print('Generated public browser fixture')
