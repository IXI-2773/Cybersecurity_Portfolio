"""Package explicitly fictional public research examples with reproducible hashes."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/data/research-examples.json'
DEST=ROOT/'assets/js/research-fixtures.js'
def render():
    data=json.loads(SOURCE.read_bytes())
    for record in data['versions']:
        record['source_hash']=hashlib.sha256(json.dumps(record,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    data['sourceHash']=hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return '// Generated by scripts/build_research_fixture.py; fictional public examples.\n(function(root){const data='+json.dumps(data,indent=2)+';root.PortfolioResearchFixtures=data;if(typeof module!=="undefined")module.exports=data;})(globalThis);\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=render():raise SystemExit('Research fixture stale: run python scripts/build_research_fixture.py')
        print('PASS: research fixture and hashes match canonical example bytes')
    else:DEST.write_text(render());print('Generated research fixture')
