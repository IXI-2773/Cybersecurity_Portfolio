"""Build technical replay data from committed public evidence only."""
import argparse
import csv
import hashlib
import json
from datetime import datetime
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'assets/js/technical-fixtures.js'
BASE=ROOT/'projects/01-authentication-detection'
def build_fixture():
    with (BASE/'validation_events.csv').open(newline='') as f:
        events=[dict(row,id=f'auth-{i+1:03d}',epochMs=int(datetime.fromisoformat(row['timestamp'].replace('Z','+00:00')).timestamp()*1000)) for i,row in enumerate(csv.DictReader(f))]
    spl=(BASE/'SPLUNK_MATRIX_BOUNDARY_RETEST.spl').read_text()
    return {'authentication':{'events':events,'expectedFindings':json.loads((BASE/'expected_findings.json').read_text())['expected_findings'],'sourceHash':hashlib.sha256((BASE/'validation_events.csv').read_bytes()).hexdigest(),'splExcerpt':spl[spl.index('| where event_type='):].strip(),'pythonExcerpt':('def find_suspicious_logins'+(BASE/'detect_auth.py').read_text().split('def find_suspicious_logins',1)[1].split('def main',1)[0]).strip(),'sources':[{ 'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in [BASE/'validation_events.csv',BASE/'expected_findings.json',BASE/'SPLUNK_MATRIX_BOUNDARY_RETEST.spl']]}}
def render():
    return '// Generated by scripts/build_technical_fixture.py; do not edit.\n(function(root){const data='+json.dumps(build_fixture(),indent=2)+';root.PortfolioTechnicalFixtures=data;if(typeof module!=="undefined")module.exports=data;})(globalThis);\n'
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=render():raise SystemExit('Technical fixture stale: run python scripts/build_technical_fixture.py')
        print('PASS: technical fixture matches canonical evidence')
    else:DEST.write_text(render());print('Generated technical fixture')
